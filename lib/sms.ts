/*
 * 문자 앱을 여는 주소 (sms:)
 * ------------------------------------------------------------------
 * 라디오 신청 · 문자 투표가 함께 쓴다. 두 화면이 각자 문자열을 만들면 한쪽만
 * 고쳐지고 다른 쪽은 조용히 안 되는 일이 실제로 있었어서(안드로이드 번호 누락)
 * 주소 만드는 규칙을 여기 한 곳에 둔다.
 *
 * 라디오 쪽(lib/radio.ts)에 두지 않는 이유는 편성표 배열이 같이 딸려 내려가지
 * 않게 하려는 것이다 — 투표 화면은 편성표가 필요 없다.
 */

/**
 * 문자 앱을 여는 주소.
 *
 * 두 가지가 기기마다 다르다.
 *
 *  1) 본문 구분자 — iOS 만 `&` 이고 나머지는 `?`(RFC 5724) 다.
 *  2) 번호 앞 `#` — 안드로이드에서는 `%23` 으로 인코딩해야 한다.
 *
 * (2)가 안드로이드 전용인 이유: `sms:#1077?body=...` 를 URI 로 읽으면 `#` 부터
 * 끝까지가 **프래그먼트**라, 크롬이 문자 앱에 넘기는 건 번호도 본문도 없는
 * 맨 `sms:` 다. 그래서 문자 앱은 열리는데 수신인 · 사연이 비어서 뜬다.
 * iOS 는 주소를 통째로 문자 앱에 넘겨 프래그먼트로 잘리지 않으므로,
 * 실기기로 검증된 형태(인코딩하지 않은 `#`)를 그대로 둔다.
 *
 * 본문이 비면 `body=` 를 아예 붙이지 않는다. 빈 값을 달아 두면 문자 앱에 따라
 * 본문 칸에 빈 줄이 들어간 채로 열린다.
 */
export function smsHref(number: string, message: string, ios: boolean): string {
  const to = ios ? number : number.replace(/#/g, "%23");
  if (!message) return `sms:${to}`;
  return `sms:${to}${ios ? "&" : "?"}body=${encodeURIComponent(message)}`;
}

/**
 * iOS 기기인지. **클릭 시점에만** 부르는 것을 전제로 한다 —
 * 렌더 중에 부르면 서버가 만든 화면과 달라져 하이드레이션이 어긋난다.
 */
export const isIosDevice = (): boolean => /iPhone|iPad|iPod/i.test(navigator.userAgent);
